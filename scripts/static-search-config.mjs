const origin = 'https://www.dhebe.com';
const host = '^dhebe\\.com$';
const publicHosts = '^(?:www\\.)?dhebe\\.com$';
const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function publicPath(value) {
  const url = new URL(value, origin);
  if (url.origin !== origin || url.search || url.hash || !/^\/(?:[a-z0-9-]+\/)*$/.test(url.pathname)
    || /^\/(?:api|private|trade|trade-history|ai-lead-agent|ai_lead_agent|shaadi|rivetprep|rostercairn)(?:\/|$)/.test(url.pathname)) throw new Error('Only canonical public website paths may have generated redirects.');
  return url.pathname;
}

export function staticRedirects(urls, aliases) {
  const routes = [...new Set(urls.map(publicPath))].filter(path => path !== '/').map(path => path.slice(1, -1));
  const alternatives = routes.map(escape).join('|');
  if (!alternatives) throw new Error('No canonical website routes.');
  return [
    ...aliases.map(([from, to]) => ({ pattern: '^' + escape(publicPath(from).slice(1, -1)) + '(?:/index\\.html|/?)$', target: origin + publicPath(to) })),
    { pattern: '^index\\.html$', target: origin + '/', explicitIndex: true },
    { pattern: '^(' + alternatives + ')/index\\.html$', target: origin + '/$1/', explicitIndex: true },
    { pattern: '^(' + alternatives + ')$', target: origin + '/$1/' },
    { pattern: '^(?:' + alternatives + '|)/?$', target: origin + '%{REQUEST_URI}', bareHost: true },
  ];
}

export function staticSearchConfig(urls, aliases) {
  const rules = staticRedirects(urls, aliases).map(rule => [
    `RewriteCond %{HTTP_HOST} ${rule.bareHost ? host : publicHosts} [NC]`,
    ...(rule.explicitIndex ? ['RewriteCond %{THE_REQUEST} "\\s/+[^?\\s]*index\\.html(?:[?\\s])" [NC]'] : []),
    `RewriteRule ${rule.pattern} ${rule.target} [R=301,L,NE]`,
  ].join('\n')).join('\n');
  return `# Generated by scripts/audit-static-site.mjs. Review before replacing server rules.
<IfModule mod_rewrite.c>
RewriteEngine On
${rules}
</IfModule>
<IfModule mod_setenvif.c>
SetEnvIf Request_URI "^/_next/static/" dhebe_immutable=1
SetEnvIf Request_URI "^/(?:api|heic|third-party)/" dhebe_noindex=1
</IfModule>
<IfModule mod_headers.c>
Header set Cache-Control "public, max-age=31536000, immutable" env=dhebe_immutable
Header set X-Robots-Tag "noindex" env=dhebe_noindex
<FilesMatch "^(?:__next\\..+|index)\\.txt$">
Header set X-Robots-Tag "noindex"
</FilesMatch>
</IfModule>
ErrorDocument 404 /404.html
`;
}
